// One guard for every inventory CLI writer. Render functions stay pure for
// byte-exact historical checks; only source writes cross this seam.
import { execFileSync } from 'node:child_process';
import { writeFile as write } from 'node:fs/promises';
import { resolve } from 'node:path';
export async function writeIntegratedArtifact(target, content, options) {
  const repo = resolve(import.meta.dirname, '..');
  try {
    execFileSync('python3', [resolve(repo,'tools/integration_candidate.py'), '--check-write', resolve(target)], {cwd: repo, input: content, stdio: ['pipe','pipe','pipe']});
  } catch {
    // The generated bytes and child diagnostics can contain internal inputs.
    throw new Error('integration generation refused: refresh main, allocate successors, then regenerate once');
  }
  return write(target, content, options);
}
